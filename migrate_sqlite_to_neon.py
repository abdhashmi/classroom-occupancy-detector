"""Safely import SQLite occupancy history into Neon PostgreSQL.

Dry-run is the default. Use --apply to write to Neon. The SQLite database is
never modified. Every row is keyed by (migration_source, legacy_id), making
repeated imports idempotent.
"""
import argparse
import os
import shutil
import sqlite3
from datetime import datetime
from pathlib import Path

import psycopg
from psycopg.rows import dict_row


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sqlite", default="occupancy.db", help="Path to existing SQLite DB")
    parser.add_argument("--apply", action="store_true", help="Actually write records to Neon")
    args = parser.parse_args()

    sqlite_path = Path(args.sqlite).expanduser().resolve()
    database_url = os.getenv("DATABASE_URL")
    if not database_url:
        raise SystemExit("DATABASE_URL is missing. Set it in the shell before running migration.")
    if not sqlite_path.is_file():
        raise SystemExit(f"SQLite database not found: {sqlite_path}")

    backup_path = sqlite_path.with_name(
        f"{sqlite_path.stem}.pre-neon-migration-{datetime.now():%Y%m%d-%H%M%S}{sqlite_path.suffix}.bak"
    )
    shutil.copy2(sqlite_path, backup_path)
    print(f"SQLite backup created: {backup_path}")

    source_key = str(sqlite_path)
    with sqlite3.connect(f"file:{sqlite_path}?mode=ro", uri=True) as source:
        source.row_factory = sqlite3.Row
        rows = source.execute("""
            SELECT id, room, count, observed_at, source
            FROM occupancy_observations ORDER BY id
        """).fetchall()
        source_count = len(rows)

    print(f"SQLite records found: {source_count}")
    if not args.apply:
        print("DRY RUN ONLY. No Neon records were written.")
        print("Review the count, then rerun with --apply to migrate.")
        return

    with psycopg.connect(
        database_url, connect_timeout=15, row_factory=dict_row
    ) as target:
        target.execute("""
            CREATE TABLE IF NOT EXISTS occupancy_observations (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                room TEXT NOT NULL,
                count INTEGER NOT NULL CHECK (count >= 0),
                observed_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                source TEXT NOT NULL DEFAULT 'unknown',
                migration_source TEXT,
                legacy_id BIGINT,
                CONSTRAINT uq_occupancy_legacy_record UNIQUE (migration_source, legacy_id)
            )
        """)
        target.execute("""
            CREATE INDEX IF NOT EXISTS idx_occupancy_room_time
            ON occupancy_observations(room, observed_at DESC)
        """)
        before = target.execute("SELECT COUNT(*) AS n FROM occupancy_observations").fetchone()["n"]
        inserted = 0
        for row in rows:
            timestamp = datetime.fromisoformat(row["observed_at"])
            result = target.execute("""
                INSERT INTO occupancy_observations
                    (room, count, observed_at, source, migration_source, legacy_id)
                VALUES (%s, %s, %s, %s, %s, %s)
                ON CONFLICT (migration_source, legacy_id) DO NOTHING
                RETURNING id
            """, (row["room"], row["count"], timestamp, row["source"], source_key, row["id"]))
            if result.fetchone() is not None:
                inserted += 1
        after = target.execute("SELECT COUNT(*) AS n FROM occupancy_observations").fetchone()["n"]

    print(f"Rows inserted this run: {inserted}")
    print(f"Neon records before: {before}; after: {after}")
    if after < source_count:
        print("WARNING: Neon total is lower than source count; check whether it already contained records.")
    else:
        print("Migration transaction committed. SQLite source and backup remain unchanged.")


if __name__ == "__main__":
    main()
