from contextlib import contextmanager
from datetime import datetime
import os
import sqlite3
from pathlib import Path


OCCUPANCY_FRESHNESS_SECONDS = 15 * 60


def _now_local_naive():
    return datetime.now()


def _configured_database_url():
    value = os.getenv("DATABASE_URL")
    if value:
        return value
    try:
        import streamlit as st
        value = st.secrets.get("DATABASE_URL")
        if value:
            return str(value)
    except Exception:
        pass
    return None


class OccupancyTracker:
    """Occupancy history backed by Neon PostgreSQL when DATABASE_URL is set.

    SQLite remains available for local-only development and as a fallback.
    PostgreSQL uses the same public methods as the original SQLite tracker.
    """

    def __init__(self, db_path="occupancy.db", database_url=None):
        self.db_path = str(db_path)
        self.database_url = database_url or _configured_database_url()
        self.is_shared = bool(self.database_url)
        if self.is_shared:
            try:
                import psycopg
            except ImportError as exc:
                raise RuntimeError(
                    "DATABASE_URL is configured but psycopg is not installed. "
                    "Install requirements.txt before starting the app."
                ) from exc
            self._initialize_postgres()
        else:
            self._initialize_sqlite()

    @contextmanager
    def _connect_sqlite(self):
        connection = sqlite3.connect(self.db_path, timeout=10)
        connection.row_factory = sqlite3.Row
        try:
            with connection:
                yield connection
        finally:
            connection.close()

    @contextmanager
    def _connect_postgres(self):
        import psycopg
        from psycopg.rows import dict_row
        with psycopg.connect(
            self.database_url, connect_timeout=15, row_factory=dict_row
        ) as connection:
            yield connection

    def _initialize_sqlite(self):
        Path(self.db_path).parent.mkdir(parents=True, exist_ok=True)
        with self._connect_sqlite() as connection:
            connection.execute("""
                CREATE TABLE IF NOT EXISTS occupancy_observations (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    room TEXT NOT NULL,
                    count INTEGER NOT NULL CHECK (count >= 0),
                    observed_at TEXT NOT NULL,
                    source TEXT NOT NULL DEFAULT 'unknown'
                )
            """)
            connection.execute("""
                CREATE INDEX IF NOT EXISTS idx_occupancy_room_time
                ON occupancy_observations(room, observed_at DESC)
            """)

    def _initialize_postgres(self):
        with self._connect_postgres() as connection:
            connection.execute("""
                CREATE TABLE IF NOT EXISTS occupancy_observations (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    room TEXT NOT NULL,
                    count INTEGER NOT NULL CHECK (count >= 0),
                    observed_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                    source TEXT NOT NULL DEFAULT 'unknown',
                    migration_source TEXT,
                    legacy_id BIGINT,
                    CONSTRAINT uq_occupancy_legacy_record
                        UNIQUE (migration_source, legacy_id)
                )
            """)
            connection.execute("""
                CREATE INDEX IF NOT EXISTS idx_occupancy_room_time
                ON occupancy_observations(room, observed_at DESC)
            """)

    def close(self):
        pass

    @property
    def observations(self):
        if self.is_shared:
            with self._connect_postgres() as connection:
                rows = connection.execute("""
                    SELECT DISTINCT ON (room) room, count, observed_at
                    FROM occupancy_observations
                    ORDER BY room, id DESC
                """).fetchall()
        else:
            with self._connect_sqlite() as connection:
                rows = connection.execute("""
                    SELECT o.room, o.count, o.observed_at
                    FROM occupancy_observations o
                    JOIN (
                        SELECT room, MAX(id) AS latest_id
                        FROM occupancy_observations GROUP BY room
                    ) latest ON latest.latest_id = o.id
                """).fetchall()
        result = {}
        for row in rows:
            try:
                timestamp = row["observed_at"] if self.is_shared else datetime.fromisoformat(row["observed_at"])
                if isinstance(timestamp, str):
                    timestamp = datetime.fromisoformat(timestamp)
            except (TypeError, ValueError):
                continue
            result[row["room"]] = {"count": int(row["count"]), "timestamp": timestamp}
        return result

    def update(self, room, count, timestamp=None, source="unknown"):
        if not isinstance(room, str) or not room.strip():
            raise ValueError("room must be a non-empty string")
        if not isinstance(count, int) or isinstance(count, bool) or count < 0:
            raise ValueError("count must be a non-negative integer")
        timestamp = timestamp or _now_local_naive()
        if not isinstance(timestamp, datetime):
            raise TypeError("timestamp must be a datetime")
        source = source.strip() if isinstance(source, str) and source.strip() else "unknown"
        if self.is_shared:
            with self._connect_postgres() as connection:
                connection.execute("""
                    INSERT INTO occupancy_observations (room, count, observed_at, source)
                    VALUES (%s, %s, %s, %s)
                """, (room.strip(), count, timestamp, source))
        else:
            with self._connect_sqlite() as connection:
                connection.execute("""
                    INSERT INTO occupancy_observations (room, count, observed_at, source)
                    VALUES (?, ?, ?, ?)
                """, (room.strip(), count, timestamp.isoformat(), source))

    def get_observations(self, rooms=None):
        """Return latest observations for many rooms using one DB round-trip.

        Args:
            rooms: Optional iterable of room IDs. When omitted, return all rooms.
        """
        room_list = list(dict.fromkeys(rooms)) if rooms is not None else None
        if room_list == []:
            return {}

        if self.is_shared:
            with self._connect_postgres() as connection:
                if room_list is None:
                    rows = connection.execute("""
                        SELECT DISTINCT ON (room) room, count, observed_at, source
                        FROM occupancy_observations
                        ORDER BY room, id DESC
                    """).fetchall()
                else:
                    rows = connection.execute("""
                        SELECT DISTINCT ON (room) room, count, observed_at, source
                        FROM occupancy_observations
                        WHERE room = ANY(%s)
                        ORDER BY room, id DESC
                    """, (room_list,)).fetchall()
        else:
            with self._connect_sqlite() as connection:
                if room_list is None:
                    rows = connection.execute("""
                        SELECT o.room, o.count, o.observed_at, o.source
                        FROM occupancy_observations o
                        JOIN (
                            SELECT room, MAX(id) AS latest_id
                            FROM occupancy_observations GROUP BY room
                        ) latest ON latest.latest_id = o.id
                    """).fetchall()
                else:
                    placeholders = ",".join("?" for _ in room_list)
                    rows = connection.execute(f"""
                        SELECT o.room, o.count, o.observed_at, o.source
                        FROM occupancy_observations o
                        JOIN (
                            SELECT room, MAX(id) AS latest_id
                            FROM occupancy_observations
                            WHERE room IN ({placeholders})
                            GROUP BY room
                        ) latest ON latest.latest_id = o.id
                    """, room_list).fetchall()

        result = {}
        for row in rows:
            try:
                timestamp = row["observed_at"] if self.is_shared else datetime.fromisoformat(row["observed_at"])
                if isinstance(timestamp, str):
                    timestamp = datetime.fromisoformat(timestamp)
            except (TypeError, ValueError):
                continue
            result[row["room"]] = {
                "count": int(row["count"]),
                "timestamp": timestamp,
                "source": row["source"],
            }
        return result

    def get_observation(self, room):
        return self.get_observations([room]).get(room)

    def get_history(self, room=None, limit=100):
        if not isinstance(limit, int) or limit < 1:
            raise ValueError("limit must be a positive integer")
        if self.is_shared:
            with self._connect_postgres() as connection:
                if room is None:
                    rows = connection.execute("""
                        SELECT id, room, count, observed_at, source
                        FROM occupancy_observations ORDER BY id DESC LIMIT %s
                    """, (limit,)).fetchall()
                else:
                    rows = connection.execute("""
                        SELECT id, room, count, observed_at, source
                        FROM occupancy_observations WHERE room = %s
                        ORDER BY id DESC LIMIT %s
                    """, (room, limit)).fetchall()
        else:
            with self._connect_sqlite() as connection:
                if room is None:
                    rows = connection.execute("""
                        SELECT id, room, count, observed_at, source
                        FROM occupancy_observations ORDER BY id DESC LIMIT ?
                    """, (limit,)).fetchall()
                else:
                    rows = connection.execute("""
                        SELECT id, room, count, observed_at, source
                        FROM occupancy_observations WHERE room = ?
                        ORDER BY id DESC LIMIT ?
                    """, (room, limit)).fetchall()
        history = []
        for row in rows:
            try:
                timestamp = row["observed_at"] if self.is_shared else datetime.fromisoformat(row["observed_at"])
                if isinstance(timestamp, str):
                    timestamp = datetime.fromisoformat(timestamp)
            except (TypeError, ValueError):
                continue
            history.append({"id": row["id"], "room": row["room"], "count": int(row["count"]),
                            "timestamp": timestamp, "source": row["source"]})
        return history

    def age_seconds(self, room, now=None):
        observation = self.get_observation(room)
        if observation is None:
            return None
        try:
            return ((now or _now_local_naive()) - observation["timestamp"]).total_seconds()
        except TypeError:
            return None

    def is_recent(self, room, max_age_seconds=OCCUPANCY_FRESHNESS_SECONDS, now=None):
        if max_age_seconds < 0:
            return False
        age = self.age_seconds(room, now)
        return age is not None and 0 <= age <= max_age_seconds

    def get_count(self, room, max_age_seconds=OCCUPANCY_FRESHNESS_SECONDS, now=None):
        observation = self.get_observation(room)
        if observation is None or not self.is_recent(room, max_age_seconds, now):
            return None
        return observation["count"]

    def get_available_rooms(self, classrooms, max_age_seconds=OCCUPANCY_FRESHNESS_SECONDS, now=None):
        return [room for room, info in classrooms.items()
                if self.get_count(room, max_age_seconds, now) == 0 and info.get("capacity", 0) > 0]
